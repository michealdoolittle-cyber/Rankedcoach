import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { getStaticPlaylistVideos } from "../worker/content-automation.mjs";
import { CURATED_PLAYLIST_RESEARCH_ARCHIVE } from "../worker/curated-playlist-research.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const collectionsPath = path.join(root, "public", "library", "gamesense-collections.js");
const mapsPath = path.join(root, "public", "library", "gamesense-maps.js");
const outputPath = path.join(root, "worker", "embedded-knowledge-sources.mjs");

function youtubeId(value = "") {
  try {
    const url = new URL(value);
    return url.searchParams.get("v") || "";
  } catch {
    return "";
  }
}

const [collectionsSource, mapsSource] = await Promise.all([
  readFile(collectionsPath, "utf8"),
  readFile(mapsPath, "utf8")
]);

const sources = new Map();
const add = source => {
  if (!/^[A-Za-z0-9_-]{11}$/.test(String(source.id || ""))) return;
  const key = `youtube:${source.id}`;
  if (!sources.has(key)) sources.set(key, {
    platform: "youtube",
    id: source.id,
    url: `https://www.youtube.com/watch?v=${source.id}`,
    title: source.title,
    channel: source.channel,
    sourceKind: source.sourceKind,
    topicType: source.topicType || "",
    entities: source.entities || [],
    startSeconds: Math.max(0, Number(source.startSeconds || 0))
  });
};

for (const video of getStaticPlaylistVideos()) {
  add({
    ...video,
    sourceKind: video.sourceType || "playlist-video",
    topicType: video.topicType || video.topicTypeOverride || "",
    entities: [video.targetName].filter(Boolean)
  });
}

for (const video of CURATED_PLAYLIST_RESEARCH_ARCHIVE) {
  add({
    ...video,
    sourceKind: video.sourceKind || video.sourceType || "curated-playlist-guide",
    topicType: video.topicType || video.topicTypeOverride || "",
    entities: video.entities || [video.targetName].filter(Boolean),
    startSeconds: video.startSeconds
  });
}

const collectionPattern = /^\s*(?:"([^"]+)"|([a-z0-9][a-z0-9-]*)):\s*\["([A-Za-z0-9_-]{11})",\s*"([^"]+)"\]/gim;
for (const match of collectionsSource.matchAll(collectionPattern)) {
  const collection = match[1] || match[2];
  add({
    id: match[3],
    title: `${collection.replace(/-/g, " ")} collection video`,
    channel: match[4],
    sourceKind: "skin-collection-video",
    topicType: "",
    entities: [collection]
  });
}

const officialVct = collectionsSource.match(/const officialVctVideo = Object\.freeze\(\["([A-Za-z0-9_-]{11})",\s*"([^"]+)"\]\)/);
if (officialVct) {
  add({
    id: officialVct[1],
    title: "Official VCT collection video",
    channel: officialVct[2],
    sourceKind: "skin-collection-video",
    topicType: "",
    entities: ["VCT cosmetics"]
  });
}

for (const match of mapsSource.matchAll(/_researchUrl:\s*"(https:\/\/www\.youtube\.com\/watch\?v=[A-Za-z0-9_-]{11})"/g)) {
  const id = youtubeId(match[1]);
  add({
    id,
    title: "Embedded map strategy research video",
    channel: "Registered Library source",
    sourceKind: "map-strategy-video",
    topicType: "Map Knowledge",
    entities: []
  });
}

const values = [...sources.values()].sort((left, right) => left.id.localeCompare(right.id));
const source = `// Generated by scripts/generate-knowledge-source-registry.mjs.\n`
  + `// Public metadata only. Transcripts and extracted claims are stored privately in KV.\n`
  + `export const EMBEDDED_KNOWLEDGE_SOURCES = Object.freeze(${JSON.stringify(values, null, 2)}.map(source => Object.freeze({\n`
  + `  ...source,\n`
  + `  entities: Object.freeze(source.entities || [])\n`
  + `})));\n`;

await writeFile(outputPath, source, "utf8");
console.log(`Registered ${values.length} embedded YouTube sources in ${path.relative(root, outputPath)}.`);
