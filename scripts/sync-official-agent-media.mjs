import { writeFile } from "node:fs/promises";
import path from "node:path";
import {
  ROOT,
  VALORANT_API_ROOT,
  fetchJson,
  loadLibraryState,
  slug
} from "./library-pipeline-core.mjs";

// Ability clips are not inferred from showcase footage.  Riot's own agent
// pages expose one mp4 per ability in __NEXT_DATA__, which lets us retain an
// exact title-to-clip match and a reviewable source URL for every entry.
const OUTPUT = path.join(ROOT, "public", "library", "gamesense-official-media.js");

function pageSlug(label = "") {
  const aliases = {
    "kay-o": "kay-o",
    "kayo": "kay-o"
  };
  const normalized = slug(label);
  return aliases[normalized] || normalized;
}

function normal(value = "") {
  return String(value)
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");
}

function extractPageVideos(html, pageUrl) {
  const raw = html.match(/<script id="__NEXT_DATA__" type="application\/json">([\s\S]*?)<\/script>/)?.[1];
  if (!raw) throw new Error("Official agent page did not include __NEXT_DATA__.");
  const page = JSON.parse(raw)?.props?.pageProps?.page;
  const groups = (page?.blades || [])
    .flatMap(blade => Array.isArray(blade?.groups) ? blade.groups : [])
    .map(group => group?.content)
    .filter(Boolean);
  const clips = new Map();
  groups.forEach(content => {
    const title = String(content?.title || "").trim();
    const src = (content?.media?.sources || []).find(source => source?.type === "video/mp4")?.src || "";
    if (title && src) clips.set(normal(title), { src, title, source: pageUrl, provider: "riot" });
  });
  return clips;
}

// Riot's agent pages sometimes group a variant/recast with its primary
// ability or prefix the displayed title with the keybind.  These are exact
// page-title aliases, not a semantic guess about an unrelated clip.
const TITLE_ALIASES = Object.freeze({
  "nebula-dissipate": "nebula",
  "astral-form-cosmic-divide": "astralformcosmicdivide",
  "astral-form": "astralformcosmicdivide",
  "cove": "covecovesmoke",
  "trailblazer": "qtrailblazer",
  "guiding-light": "eguidinglight",
  "regrowth": "cregrowth",
  "seekers": "xseekers"
});

// Riot's current agent pages publish four motion clips per Agent.  These four
// entries are passive effects (not separately equipped actions), so Riot does
// not publish a standalone clip.  Show the nearest parent-ability clip rather
// than a blank player, and retain the flag so the UI/source audit can describe
// it accurately.
const PASSIVE_CONTEXT_CLIPS = Object.freeze({
  "phoenix/heating-up": "hothands",
  "jett/drift": "updraft",
  "sova/uncanny-marksman": "huntersfury",
  "viper/toxic": "toxicscreen"
});

async function fetchOfficialPage(agent) {
  const url = `https://playvalorant.com/en-us/agents/${pageSlug(agent.label)}/`;
  const response = await fetch(url, { headers: { "User-Agent": "RankedCoach-library-media-sync/1.0" }, signal: AbortSignal.timeout(20_000) });
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  return extractPageVideos(await response.text(), url);
}

const [state, agentsPayload] = await Promise.all([
  loadLibraryState(),
  fetchJson(`${VALORANT_API_ROOT}/agents?isPlayableCharacter=true&language=en-US`)
]);
const apiById = new Map((agentsPayload.data || []).map(agent => [slug(agent.displayName), agent]));
const mediaByAgent = {};
const missing = [];

for (const agent of state.reference.agents || []) {
  const id = agent.id || slug(agent.label);
  const apiAgent = apiById.get(id);
  if (!apiAgent) {
    missing.push(`${agent.label}: absent from Valorant API`);
    continue;
  }
  try {
    const clips = await fetchOfficialPage({ label: apiAgent.displayName || agent.label });
    const abilities = {};
    for (const ability of agent.abilities || []) {
      const clip = clips.get(TITLE_ALIASES[ability.id] || normal(ability.name));
      const contextualClip = clips.get(PASSIVE_CONTEXT_CLIPS[`${id}/${ability.id}`]);
      if (clip) abilities[ability.id] = clip;
      else if (contextualClip) abilities[ability.id] = {
        ...contextualClip,
        title: `${agent.label} ability showcase`,
        contextualFallback: true
      };
      else missing.push(`${agent.label} / ${ability.name}: no exact official clip`);
    }
    mediaByAgent[id] = abilities;
  } catch (error) {
    missing.push(`${agent.label}: ${error.message}`);
  }
}

const content = `// Generated by scripts/sync-official-agent-media.mjs.\n// Every clip is an exact ability match from the official VALORANT agent page.\n(function () {\n  \"use strict\";\n  const MEDIA = Object.freeze(${JSON.stringify(mediaByAgent, null, 2)});\n  const reference = globalThis.RankedCoachGamesenseReference;\n  if (!reference) return;\n  const agents = (reference.agents || []).map(agent => ({\n    ...agent,\n    abilities: (agent.abilities || []).map(ability => ({\n      ...ability,\n      video: MEDIA[agent.id]?.[ability.id] || ability.video || null\n    }))\n  }));\n  globalThis.RankedCoachGamesenseOfficialMedia = MEDIA;\n  globalThis.RankedCoachGamesenseReference = Object.freeze({ ...reference, agents: Object.freeze(agents) });\n})();\n`;
await writeFile(OUTPUT, content, "utf8");

const total = (state.reference.agents || []).reduce((sum, agent) => sum + (agent.abilities || []).length, 0);
const covered = Object.values(mediaByAgent).reduce((sum, abilities) => sum + Object.keys(abilities).length, 0);
console.log(`Official ability media: ${covered}/${total} clips written to ${path.relative(ROOT, OUTPUT)}.`);
if (missing.length) {
  console.log("Unmatched official media:");
  missing.forEach(row => console.log(`- ${row}`));
}
