import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  DRAFT_ROOT,
  VALORANT_API_ROOT,
  fetchJson,
  patchLabel
} from "./library-pipeline-core.mjs";
import {
  auditLibraryDrafts,
  renderLibraryAuditMarkdown
} from "./knowledge-library-audit.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const reportRoot = path.join(root, "docs", "reports");
const date = new Date().toISOString().slice(0, 10);
const outputPath = path.join(reportRoot, `knowledge-library-review-${date}.md`);
const workerBaselinePath = path.join(root, "worker", "knowledge-library-audit-baseline.mjs");
const version = await fetchJson(`${VALORANT_API_ROOT}/version`);
const currentPatch = patchLabel(version.data);
const audit = await auditLibraryDrafts(DRAFT_ROOT, { currentPatch });

await mkdir(reportRoot, { recursive: true });
await writeFile(outputPath, renderLibraryAuditMarkdown(audit), "utf8");
const workerBaseline = {
  generatedAt: audit.generatedAt,
  status: audit.status,
  scope: audit.scope,
  sourceCoverage: audit.sourceCoverage,
  approval: audit.approval,
  missingOpportunities: audit.missingOpportunities,
  duplicateConceptCount: audit.duplicateConcepts.length,
  conflictCandidateCount: audit.conflictCandidates.length,
  outdatedCount: audit.outdated.length,
  consensusSummary: audit.consensusSummary
};
const compactKnowledgeRows = audit.knowledgeIndex.map(item => [
  item.id,
  item.type,
  item.topic,
  item.entities,
  item.stance,
  item.tokens,
  item.sourceId,
  item.evidenceUrl
]);
await writeFile(
  workerBaselinePath,
  `// Generated by scripts/review-library-knowledge.mjs. Transcript-free audit metadata only.\n`
    + `export const LIBRARY_KNOWLEDGE_AUDIT_BASELINE = Object.freeze(${JSON.stringify(workerBaseline, null, 2)});\n`
    + `// Server-only comparison index. This contains normalized concepts, not source wording.\n`
    + `const LIBRARY_KNOWLEDGE_INDEX_ROWS = Object.freeze([\n${compactKnowledgeRows.map(row => JSON.stringify(row)).join(",\n")}\n]);\n`
    + `export const LIBRARY_KNOWLEDGE_INDEX = Object.freeze(LIBRARY_KNOWLEDGE_INDEX_ROWS.map(row => Object.freeze({\n`
    + `  id: row[0], type: row[1], topic: row[2], entities: Object.freeze(row[3]), stance: row[4],\n`
    + `  tokens: Object.freeze(row[5]), sourceId: row[6], evidenceUrl: row[7]\n`
    + `})));\n`,
  "utf8"
);

console.log(`Knowledge review complete: ${path.relative(root, outputPath)}`);
console.log(JSON.stringify({
  status: audit.status,
  scope: audit.scope,
  sourceCoverage: audit.sourceCoverage,
  approval: audit.approval,
  missingOpportunities: audit.missingOpportunities.length,
  duplicateConcepts: audit.duplicateConcepts.length,
  conflictCandidates: audit.conflictCandidates.length,
  outdated: audit.outdated.length
}, null, 2));
